export const DICTIONARIES: Record<UiLanguage, Record<TKey, string>> = { en, bn }

export type Translate = (key: TKey, vars?: Record<string, string | number>) => string

export function translate(language: UiLanguage, key: TKey, vars?: Record<string, string | number>): string {
  const template = DICTIONARIES[language][key] ?? en[key]
  if (!vars) return template
  return template
    // {count|profile|profiles} picks the singular form when count is exactly 1.
    .replace(/\{(\w+)\|([^|{}]+)\|([^|{}]+)\}/g, (match, name: string, one: string, many: string) =>
      name in vars ? (Number(vars[name]) === 1 ? one : many) : match
    )
    .replace(/\{(\w+)\}/g, (match, name: string) => (name in vars ? String(vars[name]) : match))
}

